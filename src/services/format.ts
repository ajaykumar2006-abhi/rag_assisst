/** Split an answer into text and `[n]` citation markers for interactive rendering. */
export interface AnswerSegment {
  kind: "text" | "citation";
  value: string;
  index?: number;
}

export function parseAnswerSegments(answer: string): AnswerSegment[] {
  const segments: AnswerSegment[] = [];
  const pattern = /\[(\d+)\]/g;
  let cursor = 0;
  let match: RegExpExecArray | null;

  while ((match = pattern.exec(answer)) !== null) {
    if (match.index > cursor) {
      segments.push({ kind: "text", value: answer.slice(cursor, match.index) });
    }
    segments.push({ kind: "citation", value: match[0], index: Number(match[1]) });
    cursor = match.index + match[0].length;
  }
  if (cursor < answer.length) {
    segments.push({ kind: "text", value: answer.slice(cursor) });
  }
  return segments;
}

export function truncate(value: string, limit: number): string {
  if (value.length <= limit) return value;
  return `${value.slice(0, Math.max(0, limit - 1)).trimEnd()}…`;
}

export function pluralize(count: number, singular: string, plural?: string): string {
  return count === 1 ? singular : (plural ?? `${singular}s`);
}
